ORG 00H
MOV 30H,#1 ; OPTION SELECTION
MOV 31H,#21 ;AGE 
MOV 32H,#1; MALE OR FEMALE >40

MOV 35H,#00 ; IF 1 HE DISPLAY FOR AGE >40


MAIN:	
MOV A,30H

CJNE A,#1,COVIDCHEACK
ACALL CECKUP
SJMP EXIT

COVIDCHEACK:
CJNE A,#2,EXIT
ACALL COVID



EXIT:
SJMP EXIT


CECKUP:
MOV A,31H
; DIVIDE THE AGE BY 10
MOV B,#10
DIV AB
; IF result <2 LEVEL 1 ( 10-19)
; IF results <4 LEVEL 2 ( 20-39)
; IF results =0 LEVEL 3 ( 40 -99)
; 
CJNE A,#2,NEXT1
NEXT1:
JNC LEVEL2 ; IF >=2
;ESLE REMIDER<2 SO, LEVEL1
MOV 35H,#1
SJMP EE

LEVEL2:
CJNE A,#4,NEXT2
NEXT2:
JNC LEVEL3 ; IF >=4
;ESLE REMIDER<2 SO, LEVEL1
MOV 35H,#2
SJMP EE

LEVEL3:
MOV A,32H
CJNE A,#1,FEMALE
MOV 35H,#3
SJMP EE

FEMALE:
MOV 35H,#4
SJMP EE

EE:
RET
;--------PRODURE 2------
COVID:
MOV A,31H  ; AGE

CJNE A,#5,NEXT
NEXT:
JNC OKAY ; IF >=5
;ESLE REMIDER<5 SO, NO
MOV 35H,#5
SJMP EEE

OKAY:
MOV 35H,#6

EEE:
RET
