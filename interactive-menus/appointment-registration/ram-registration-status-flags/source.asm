ORG 00H

; 1--> FOR YES , 0--> FOR NO
MOV 30H,#0 ; TESTED FOR CORONA +VE OR NOT
MOV 31H,#4 ;MONTH WHEN YOU CATCH CORONA
MOV 32H,#1 ;TAKE FIRST DOZE
MOV 36H,#11 ; FIRST DOZE DATA IF TAKEN

;RANDOM INITIAL VALUES
MOV 33H,#1 ; APPOINTMENT OF DOZE
MOV 34H,#100  ; DAY OF DOZE
MOV 35H,#1  ; CONFIRM



START:

MOV A,30H
CJNE A,#0,POSITIVE
ACALL NEG
SJMP BACK

POSITIVE:
CJNE A,#1,ERROR
ACALL POS
SJMP BACK

ERROR:

SJMP BACK

BACK:
SJMP START


;*************
NEG:

;Did You take first doze?
MOV A,32H
CJNE A,#0,SecondDozee
MOV 34H,#0 ; TOMORROW 
SJMP BACK3

SecondDozee:
; DATA OF FIRST DOZE

CJNE A,#1,ERROR3
MOV R7,36H
MOV A,R7
ADD A,#2
ACALL CHEACK
MOV 33H,A ;MONTH OF DOZE
MOV 34H,#4 ; DAY OF DOZE

SJMP BACK3

ERROR3:
SJMP BACK3
BACK3:
ACALL CONFIRM
RET
;*************
POS:
; WHEN YOU CATCH CRONA?
MOV R7,31H
;Did You take first doze?
MOV A,32H
CJNE A,#0,SecondDoze
;appointment of 1st doze
MOV A,R7
ADD A,#3
ACALL CHEACK
MOV 33H,A ;MONTH OF DOZE
MOV 34H,#1 ; DAY OF DOZE

SJMP BACK1

SecondDoze:
CJNE A,#1,ERROR1
;APPOINTMENT OF 2ND DOZE AFTER 4 MONTH
MOV A,R7
ADD A,#4
ACALL CHEACK
MOV 33H,A ;MONTH OF DOZE
MOV 34H,#2 ; DAY OF  DOZE
SJMP BACK1

ERROR1:

BACK1:
ACALL CONFIRM

RET

;**********
CHEACK:
CJNE A,#12,CONTINUE
SJMP BACK2
CONTINUE:
JC BACK2  ; SKIP IF CARRY FLAG =1, WHICH MEAN THAT A<12
SUBB A,#12

BACK2:
RET

;**********
CONFIRM:
MOV A,35H
CJNE A,#1,CONFIRM

RET


