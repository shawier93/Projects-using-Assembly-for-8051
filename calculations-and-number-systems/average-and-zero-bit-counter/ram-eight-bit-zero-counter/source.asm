ORG 0H
MENU:
MOV R7,#2
CJNE R7,#1, LOOP2
LOOP1:
MOV R1,#90
MOV A,R1 ;A=90
ADD A,#1 ;A=91
ADD A,R1 ; A=91+90
MOV B,#2
DIV AB
SJMP $

LOOP2:
CJNE R7,#2,LOOP3
MOV R1,#30H ;R1=30H
MOV R5,#8
MOV 10H,#0 ; COUNTER ZEROS
MOV A,R1 ;A=30H
X8: ; COUNTING NUMBER OF ZEROS
RRC A ; EVERY VALUE INSIDE C
JNC ZEROS
DJNZ R5,X8 ;CHECKING NEXT NO.
SJMP $



ZEROS:
INC 10H
DJNZ R5,X8
SJMP $

LOOP3:
CJNE A,#3,MENU
SJMP $ 
END
