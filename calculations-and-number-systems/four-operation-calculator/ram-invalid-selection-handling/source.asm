ORG 00H

MOV 30H,#4 ; SELECTED OPERATION
; 1 --> SUM
; 2--> SUB
; 3--> MUL
; 4--> DIV
MOV 40H,#6
MOV 41H,#3
MOV 50H,#00 ; RESULT
MOV 51H,#00 ; REMINDER

START:
MOV A,30H
CJNE A,#1,SUBTRACT
MOV A,40H
ADD A,41H
MOV 50H,A
SJMP NEXT


SUBTRACT:
CJNE A,#2,MULTIPLICATION
MOV A,40H
SUBB A,41H
MOV 50H,A
SJMP NEXT

MULTIPLICATION:
CJNE A,#3,DIVISION
MOV A,40H
MOV B,41H
MUL AB
MOV 50H,A
SJMP NEXT

DIVISION:
CJNE A,#4,WRONG
MOV A,40H
MOV B,41H
DIV AB
MOV 50H,A
MOV 51H,B
SJMP NEXT

WRONG: 
SJMP START

NEXT:
SJMP NEXT

ORG 300H
NUM1: DB 6
	  DB 0
NUM2: DB 3
	  DB 0
END
