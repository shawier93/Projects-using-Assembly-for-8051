ORG 00H 
MOV 10H,#2; SELETCTION 
MOV R1,#23H
MOV 20H,#4 ; FIRST NUMBER
MOV 21H,#2 ;SECOND NUMBER
MOV 22H,#3 ;3RD NUMBER
MOV 30H,#00H ; NTH VALUE

START:
MOV A,10H
CJNE A,#1,OPTION2
MOV A,#6; NUMBER OF ELEMENTS
ACALL PERRINSEQ
SJMP EXIT 

OPTION2:
CJNE A,#2,OPTION3
ACALL NthNumber
SJMP EXIT 

OPTION3:
CJNE A,#2,WRONG
SJMP EXIT

WRONG:
SJMP START

EXIT:
SJMP $


PERRINSEQ:
MOV R7,A
MOV R1,#23H
MOV R0,#22H
ST:
INC R0
MOV A,R0
DEC R0
DEC R0
MOV A,@R0
DEC R0 
ADD A,@R0
MOV R3,A
MOV A,R0
ADD A,#3
MOV R0,A
MOV A,R3
MOV @R0,A
DJNZ R7,ST

RET

NthNumber:
MOV A,#6
SUBB A,#3
ACALL PERRINSEQ
MOV 30H,R3

RET

END
