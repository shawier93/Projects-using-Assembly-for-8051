ORG 00H

START:
MOV TMOD,#01
MOV R6,#3 ; COUNTER FOR THREE CASES 
;EACH TRAFFIC LIGHT HAS A TURN 
; EACH TRAFFIC LIGH IS CONNECTED TO ONE PORT

TRRAFIC:
MOV A,R6


CJNE A,#3,CASE2
MOV R1,#1H
MOV R2,#4H
MOV R3,#4H
MOV R4,#1H
MOV R5,#2H
MOV R0,#4H
SJMP BACK

CASE2:
CJNE A,#2,CASE1
MOV R1,#4H
MOV R2,#1H
MOV R3,#4H
MOV R4,#4H
MOV R5,#1H
MOV R0,#2H

SJMP BACK
CASE1:
MOV R1,#4H
MOV R2,#4H
MOV R3,#1H
MOV R4,#2H
MOV R5,#4H
MOV R0,#1H
BACK:

MOV P1,R1 ; TURN ON  GREEN LED
MOV P2,R2 ; RED
MOV P3,R3  ; RED
MOV R7,#40  ; 2SEC DEALY
ACALL DELAY
; MAKE IT ORANGE AT THE LSTA SECOND OF THE FIRST ONE 
MOV P1,R4 ; 
MOV P2,R5  ;
MOV P3,R0  
MOV R7,#20  ; 1SEC DEALY
ACALL DELAY

DJNZ R6,TRRAFIC

SJMP START

DELAY:
; DELAY = 50ms * R7 
; FOR 1 SEC -->R7= 20
; FOR 2 SEC --> R7=40 
MOV R7,#20
AGAIN:
MOV TH0,#3CH
MOV TL0,#0ADH
SETB TR0
HERE: JNB TF0,HERE
CLR TR0
CLR TF0
DJNZ R7,AGAIN
RET

END
