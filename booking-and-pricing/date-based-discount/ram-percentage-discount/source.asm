
ORG 000H
MOV R3,#20 ; AMOUNT OF MONEY 
MOV R4,#12 ; DAYS  
MOV R5,#0 ; DISCOUNT PERCENTAGE  0,1,2,10 /10

MAINMENUE:
MOV A,R4
SUBB A,#1

CJNE A,#0H,CASE2;
MOV R5,#0H
AJMP CALC

CASE2: 
CJNE A,#10, CASE3
CASE3:
JNC CASE4 ;  A>=10 ELSE CONTINE
; LESS THAN 9
MOV R5,#1
AJMP CALC

CASE4:  CJNE A,#20, CASE5
CASE5:
JNC CASE6 ;  A>=20 ELSE CONTINE
; LESS THAN 19
MOV R5,#2
AJMP CALC

CASE6:
MOV R5,#10
AJMP CALC



CALC:
MOV B,R5;
MOV A,R3
MUL AB
MOV B,#10;
DIV AB
MOV R5,A ; DISCOUNT AMOUNT
MOV A,R3
SUBB A,R5
MOV R6,A

