MOV 30H,#27H	; AMOUNT OF SHIP
MOV 31H,#9	;DATE OF TODAY
MOV 32H,#0; DISCOUNT
MOV 33H,#0	; TOTAL COST

CHECK:
MOV A,31H
MOV B,#1
;DAYS LATE 
SUBB A,B;

; DEVIDE THE DAYS BY 10 
MOV B,#10   ; 0,7, 17, 27
DIV AB  ; A = 0 OR 1 OR 2,3,4..
MOV R1,B
;-----------------
CJNE A,#0H, DISCO2 
CJNE R1,#0H, DISCO1
MOV 32H,#0;
ACALL COST
AJMP CHECK

DISCO1:  ; 10% DISCOUNT
CJNE A,#0H, DISCO2
MOV 32H,#1;   10%   1/10
ACALL COST
AJMP CHECK

DISCO2: 	;20% DISCOUNT
CJNE A,#1H, FREE
MOV 32H,#2;    20%   2/10
ACALL COST
AJMP CHECK

FREE:
MOV 32H,#10;
ACALL COST
AJMP CHECK



COST:
MOV A,30H  ; MOVE ANOUNT TO A
MOV B,#10
DIV AB    ; DIV A/10
MOV R3,A; HOLD A VALUE
MOV A,#10
SUBB A,32H  ; 10 - DISOUNT ( 0,1,2,10)
MOV B,A
MOV A,R3
MUL AB   ; REBECK THE VALUE { (A/10)(10- DIS ) } 
MOV 33H,A

;  20 - 0.1*20  = 2(10-1)

RET


