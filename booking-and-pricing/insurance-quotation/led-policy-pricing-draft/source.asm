ORG 00H

MOV 30H,#2  ; CATEGORY
MOV 31H,#2	; INSURANCE
MOV 32H,#1	;ABROAD INSURANCE
MOV 33H,#1	;MEMEBESHIP DISOUNT
MOV 34H,#4	;SUBSCRIPTION YEARS

MOV 35H,#0 ;  final COST
MOV 36H,#0	;COST


MAIN:
ACALL FLASH

MOV A,30H
CJNE A,#1,CAT2
MOV 36H,#35
AJMP WARR

CAT2:
CJNE A,#2,CAT3
MOV 36H,#28
AJMP WARR

CAT3:
CJNE A,#3,ERROR
MOV 36H,#44
AJMP WARR

ERROR:
SJMP MAIN

WARR: 
ACALL INSURANCE
ACALL ABROADINSURNCE
ACALL MEMBERSHIP
ACALL SUBSCRIPTION
MOV 35H,36H

ACALL FLASH

AJMP ENDD


;--------------------
;---------------------------
