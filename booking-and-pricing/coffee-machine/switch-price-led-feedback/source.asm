
ORG 000H
; DEFINE 
MOV P2,#0FFH ; INPUT
MOV P1,#00H ; OUTPUT 00000000B
MOV R7,#0FFH ; LEDS CONTER
MOV R5,#0 ; TO HOLD ANY ADDITIONAL COST
MOV R4,#0 ; COST X
MOV R3,#0 ; COST Y

MOV 40H,#0 ; TO SAVE THE TYPE CHOICE 
MOV 41H,#0 ;  TO SAVE THE SIZE CHOICE 
MOV 42H,#0 ; TO SAVE THE MILK TYPE
MOV 43H,#0 ; TO SAVE THE SUGAR LEVEL
MOV 45H,#0 ; TO SAVE THE TOTAL COST

MAIN:
ACALL LED
ACALL DELAY
ACALL SHOW_CASH
ACALL LED

;READ SW0,SW1
MOV R6,#00000011B
ACALL READ
ACALL TYPE
ACALL LED

;READ SW2,SW3
MOV R6,#00001100B
ACALL READ
ACALL SIZE
ACALL LED

;READ SW4,SW5
MOV R6,#00110000B
ACALL READ
ACALL MILK
ACALL LED

;READ SW6,SW7
MOV R6,#11000000B
ACALL READ
ACALL SUGAR
ACALL LED

; CALCULATE THE COST
ACALL COST
ACALL LED
ACALL DELAY
ACALL DELAY
ACALL SHOW_COST
ACALL FLASH




SJMP $




;============
SHOW_CASH:
MOV A,#CASHX
CPL A
MOV P1,A
ACALL DELAY
MOV A,#CASHY
CPL A
MOV P1,A
ACALL DELAY
RET
;-------
READ:
MOV A,P2
ANL A,R6   ; 0000XX00
RET
;--------------
TYPE:
CJNE A,#00H, NEXT1
MOV R3,#AMER
MOV 40H,#1  
SJMP BACK
NEXT1:
CJNE A,#01H,NEXT2
MOV R3,#CAP
MOV 40H,#2
SJMP BACK
NEXT2:
CJNE A,#02H,NEXT3
MOV R3,#LATTE
MOV 40H,#3
SJMP BACK
NEXT3:
CJNE A,#03H,ERROR
MOV R4,#MOCHA
MOV 40H,#4
SJMP BACK
ERROR:
BACK:
RET
;----------------


SIZE:
CJNE A,#0000B, NEXTT1
MOV R5,#SMALL
MOV 41H,#1
SJMP BACK1
NEXTT1:
CJNE A,#0100B,NEXTT2
MOV R5,#MED
MOV 41H,#2
SJMP BACK1
NEXTT2:
CJNE A,#1000B,ERROR1
MOV R5,#LARGE
MOV 41H,#3
SJMP BACK1

ERROR1:
BACK1:
RET
;-------
MILK:
CJNE A,#000000B, NEXTTT1
MOV 42H,#1
SJMP BACK2
NEXTTT1:
CJNE A,#010000B,NEXTTT2
MOV 42H,#2
SJMP BACK2
NEXTTT2:
CJNE A,#100000B,ERROR2
MOV 42H,#3
SJMP BACK2

ERROR2:
BACK2:
RET
;----------
SUGAR:
CJNE A,#00000000B, NEXTTT11
MOV 43H,#1
SJMP BACK3
NEXTTT11:
CJNE A,#01000000B,NEXTTT22
MOV 43H,#2
SJMP BACK3
NEXTTT22:
CJNE A,#10000000B,NEXTTT33
MOV 43H,#3
SJMP BACK3
NEXTTT33:
CJNE A,#11000000B,ERROR3
MOV 43H,#4
SJMP BACK3

ERROR3:
BACK3:
RET
;-----
COST:
MOV A,R3
ADD A,R5
MOV R3,A 
MOV B,#100
DIV AB
MOV R3,B
ADD A,R4
MOV R4,A
RET
;---
SHOW_COST:
MOV A,R4
CPL A
MOV P1,A
ACALL DELAY
MOV A,R3
CPL A
MOV P1,A
ACALL DELAY
ACALL DELAY
RET
;-----
LED:
; 
MOV A,R7
CLR C
RRC A
MOV R7,A
ACALL DELAY
MOV P1,R7
ACALL DELAY
RET
;-----
FLASH:
MOV R0,#6
MOV A,#0FFH
RE:
CPL A
MOV P1,A
ACALL DELAY
DJNZ R0,RE

MOV P1,#00
RET
;-----
DELAY:
; DELAY FOR 10 MS
; FFRE1 =12MH
; DELAY= (1+ 2*100 + (1+200+2)*49  )*1uS= 10,000US
MOV R1,#49;
HERE:
MOV R2,#100;
HERE1: DJNZ R2,HERE1
DJNZ R1,HERE
RET
;------
;-------
ORG 30H
CASHX EQU 5  ; ENTERED MONEY  X
CASHY EQU 75  ; ENTERED MONEY Y

AMER EQU 50   ; 0.5
CAP EQU 75   ; 0.75
LATTE EQU 75  ; 0.75
MOCHA EQU 1	 ; 1 KD

SMALL EQU 0 ; 0 ADDITIONAL COST
MED EQU 25 ; O.25 KD
LARGE EQU 50; 0.50

TIME_DELAY EQU 10 ; 10ms

END

