CASH:
	MOV	A,30H
	CPL	A				;its cpl FOR 1=ON & 0=OFF
	MOV	P1,A			;SEND CASH X TO LEDS
	ACALL DELAY
	MOV	A,31H
	CPL	A				; its cpl FOR 1=ON & 0=OFF
	MOV	P1,A			;SEND CASH Y TO LEDS
	RET

PROGRAM_ROM: ;save locations in rom
	MOV	DPTR,#INX
	CLR	A
	MOVC A,@A+DPTR
	MOV	30H,A
	MOV	DPTR,#INY
	CLR	A
	MOVC A,@A+DPTR
	MOV	31H,A
	MOV	DPTR,#TIME_DELAY
	CLR	A
	MOVC A,@A+DPTR
	MOV	32H,A
	RET

























DELAY:
	PUSH 0
	PUSH 1
	PUSH 2
	MOV	R0,#4
L1:	MOV	R1,#250
L2:	MOV R2,32H			;GET TIME DELAY VALUE
L3:	DJNZ R2,L3
	DJNZ R1,L2
	DJNZ R0,L1
	POP 2
	POP 1
	POP 0
	RET


INX:	DB	3
INY:	DB	75
TIME_DELAY:	DB	100


	END
