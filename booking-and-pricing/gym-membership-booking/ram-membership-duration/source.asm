ORG 000H

MOV 40H,#5   ;VIP M 
MOV 41H,#5	;VIP Y
MOV 42H,#30	;ONLINE M
MOV 43H,#30	;ONLINE Y
MOV 44H,#20	;REG M
MOV 45H,#20	;REG Y
MOV 30H,#2	;MEMEBERSHIP TYPE
MOV R2,#1	; MONTHLY OR YEARLY 
MOV 31H,#2	; DURATION
MOV 32H,#0	; COST
MOV 33H,#0 	;COST

START:

MOV A,30H
CJNE A,#1,NEXT
ACALL VIP
AJMP START 

NEXT: CJNE A,#2,NEXT1
ACALL ONLINE
AJMP START 

NEXT1: CJNE A,#3,NEXT2
ACALL REGULAR
AJMP START 

NEXT2: 
ACALL WRONG
AJMP START 


;/////////////////////////////
VIP:
MOV A,R2;
CJNE A,#1,YEAR
MOV A,#35 	;AMOUNT
MOV B,31H	;DURATION 
MUL AB
MOV 32H,A    ; TOTAL COST
MOV 33H,B
SJMP END

YEAR:
CJNE A,#2, END
MOV A,#99	;AMOUNT
MOV B,31H	;DURATION 
MUL AB
MOV 32H,A    ; TOTAL COST
MOV 33H,B

END:
RET
;//////////////////////////////
ONLINE:
MOV A,R2;
CJNE A,#1,YEAR1
MOV A,#5 	;AMOUNT
MOV B,31H	;DURATION 
MUL AB
MOV 32H,A    ; TOTAL COST
MOV 33H,B
SJMP END1

YEAR1:
CJNE A,#2, END1
MOV A,#30 	;AMOUNT
MOV B,31H	;DURATION 
MUL AB
MOV 32H,A    ; TOTAL COST
MOV 33H,B

END1:
RET

REGULAR:
MOV A,R2;
CJNE A,#1,YEAR2
MOV A,#10 	;AMOUNT
MOV B,31H	;DURATION 
MUL AB
MOV 32H,A    ; TOTAL COST
MOV 33H,B
SJMP END2

YEAR2:
CJNE A,#2, END2
MOV A,#70 	;AMOUNT
MOV B,31H	;DURATION 
MUL AB
MOV 32H,A    ; TOTAL COST
MOV 33H,B

END2:
RET

WRONG:
MOV 32H,#0   ; TOTAL COST 0 
MOV 33H,#0
RET
