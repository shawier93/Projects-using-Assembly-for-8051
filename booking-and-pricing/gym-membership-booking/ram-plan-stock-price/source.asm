ORG 0H
MOV 30H,#2 ; MEMPERSHIP TYPE 
MOV 31H,#1 ;MEMPERSHIP DURATION
MOV 32H,#0
MOV 40H,#5 ;LIMIT # OF VIP MONTHLY
MOV 41H,#5 ;LIMIT # OF VIP YEARLY
MOV 42H,#30 ;LIMIT # OF ONLINE MONTHLY
MOV 43H,#30 ;LIMIT # OF ONLINE YEARLY
MOV 44H,#20 ;LIMIT # OF REGULAR MONTHLY
MOV 45H,#20 ;LIMIT # OF REGULAR YEARLY

MOV A,30H
CJNE A,#1,ONLINE

VIP:
MOV A,31H
CJNE A,#1,YEARLY

MONTHLY:
MOV R1,40H
DJNZ R1,NEXT
SJMP WRONG

NEXT:
CLR A
DEC 40H
MOV DPTR,#VIPM
MOVC A,@A+DPTR
MOV 32H,A
SJMP OUT

YEARLY:
CJNE A,#2,VIP
MOV R2,41H
DJNZ R2,NEXT2
SJMP WRONG 

NEXT2:
CLR A
DEC 41H
MOV DPTR,#VIPY
MOVC A,@A+DPTR
MOV 32H,A
SJMP OUT




ONLINE:
CJNE A,#2,REGULAR
MOV A,31H
CJNE A,#1,YEARLY2

MONTHLY2:
MOV R1,42H
DJNZ R1,NEXT3
SJMP WRONG

NEXT3:
CLR A
DEC 42H
MOV DPTR,#ONM
MOVC A,@A+DPTR
MOV 32H,A
SJMP OUT

YEARLY2:
CJNE A,#2,ONLINE
MOV R2,43H
DJNZ R2,NEXT4
SJMP WRONG 

NEXT4:
CLR A
DEC 43H
MOV DPTR,#ONY
MOVC A,@A+DPTR
MOV 32H,A
SJMP OUT



REGULAR:
CJNE A,#3,WRONG
MOV A,31H
CJNE A,#1,YEARLY3

MONTHLY3:
MOV R1,44H
DJNZ R1,NEXT5
SJMP WRONG

NEXT5:
CLR A
DEC 44H
MOV DPTR,#REGM
MOVC A,@A+DPTR
MOV 32H,A
SJMP OUT

YEARLY3:
CJNE A,#2,REGULAR
MOV R2,45H
DJNZ R2,NEXT6
SJMP WRONG 

NEXT6:
CLR A
DEC 45H
MOV DPTR,#REGY
MOVC A,@A+DPTR
MOV 32H,A
SJMP OUT

WRONG:
SJMP $

VIPM: DB 35
VIPY: DB 99
ONM: DB 5
ONY: DB 30
REGM: DB 10
REGY: DB 70

OUT:
END
